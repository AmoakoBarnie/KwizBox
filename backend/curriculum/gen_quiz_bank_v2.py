def make_better_question(code, name, indicator):
    iid = indicator['indicator_id']
    raw_text = indicator['text']
    cs_id = indicator['cs_id']
    cs_text = indicator['cs_text']
    level = indicator.get('level', 'B4')
    
    # Clean the text
    text = strip_intro(raw_text)
    if not text:
        text = raw_text
    
    # Build a question phrase
    # Identify if it ends with a natural question trigger
    if text.endswith('?'):
        qtext = text
    elif any(text.lower().endswith(word) for word in ['.', ',', ';', ':']):
        qtext = text.rstrip('.,;:').strip()
        if not qtext.endswith('?'):
            qtext += '?'
    else:
        qtext = text
        if not qtext.endswith('?'):
            qtext += '?'
    
    # Capitalize first letter
    qtext = qtext[0].upper() + qtext[1:]
    
    # Remove trailing competency codes in question text too
    qtext = re.sub(r'\s+[A-Z]{2,3}\.\d{1,2}\.\d{1,2}\.\d{1,2}\s*[-:]*.*$', '', qtext)
    qtext = re.sub(r'\s+[A-Z]{2}\d{1,2}\.\d{1,2}\s*[-:]*.*$', '', qtext)
    qtext = qtext.strip()
    if not qtext.endswith('?'):
        qtext += '?'
    
    # Create 4 plausible options
    # 1 correct = the stripped indicator text
    correct = qtext.rstrip('?')
    
    # Generate 3 related-but-wrong options based on the subject
    distractors = [
        f"This describes a different indicator in the {name} curriculum.",
        f"This refers to a concept not covered by indicator {iid}.",
        f"This describes a skill from another strand of {name}.",
        f"This relates to a different content standard in {name}.",
        f"This option is not correct according to the NaCCA {name} curriculum.",
        f"This describes an unrelated learning outcome in {name}.",
        f"This is not the correct answer for indicator {cs_id}.",
        f"This refers to a different topic in the {name} standards.",
        f"The correct indicator for this question is {iid}.",
        f"This describes a learning outcome from a different subject.",
    ]
    
    # Pick 3 distractors not matching correct
    chosen = []
    for d in distractors:
        if d not in chosen and d != correct and len(chosen) < 3:
            chosen.append(d)
    
    while len(chosen) < 3:
        chosen.append(f"This describes a different indicator in the {name} curriculum.")
    
    random.shuffle(chosen)
    options = [correct] + chosen[:3]
    random.shuffle(options)
    correct_idx = options.index(correct)
    
    return {
        'id': f"{code}-{iid}",
        'subject': name,
        'subject_code': code,
        'class_level': level,
        'strand': '',
        'sub_strand': '',
        'cs_id': cs_id,
        'indicator_id': iid,
        'question': qtext,
        'options': options,
        'answer_index': correct_idx,
        'explanation': f"Based on NaCCA curriculum indicator {iid} under content standard {cs_id} for {name}."
    }

